<p>9번과 4번은 행동을 밖으로 표출하게 하는 척도이고, 2번, 0번, 7번은 행동을 억제하고 내부로 향하게 하는 척도다. 같은 6번 상승이라도 9번이 함께 높으면 의심을 공격적으로 행동화할 수 있고, 2번과 0번이 함께 높으면 우울하게 위축된다. <b>전문가는 높은 척도 하나만 보지 않고 그 척도의 “에너지”를 결정하는 다른 척도를 함께 본다.</b></p>

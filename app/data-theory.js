<p>2번(우울)·7번(불안)·9번(활력) 등은 현재 상태에 민감하게 반응한다. 4번·0번·5번은 시간이 지나도 비교적 안정적인 특성 척도다. 재검사에서 2번이 떨어지고 4번이 그대로라면 “위기가 지나간 뒤에도 성격적 문제는 남았다”는 뜻이다.</p>
